export interface H3ExampleReference { id: string; label: string }

export interface H3Example extends H3ExampleReference {
  style: string
  style_label: string
  topics: string[]
  excerpt: string
  w: number
  h: number
  seconds: number
  shots: number
  thumbnail_url: string
  video_url: string
  description?: string
  visual_treatment?: string
  camera?: string
  soundscape?: string
  music?: string
  prompt?: string
  source_url?: string
  atlas_url?: string
}

export function parseH3ExampleHref(href: string): string | null {
  return /^stimma-h3:(\d{6})$/.exec(href)?.[1] ?? null
}

const HEADER = '> **Style inspiration (H3 examples):**'
const GUIDANCE = '> Adapt the selected look and camera to my scene. Read the original with library(action="prompt_examples", filters={"example_id":"ID"}). Preserve my story and dialogue; borrow sound only if requested. These are style inspirations, not media inputs.'

export function formatH3References(references: H3ExampleReference[]): string {
  if (!references.length) return ''
  return [HEADER, ...references.map(({ id, label }) => {
    const clean = label.replace(/[\r\n\[\]\\]/g, ' ').trim() || `H3 ${id}`
    return `> - [${clean}](stimma-h3:${id})`
  }), GUIDANCE].join('\n')
}

export function parseH3References(source: string | null | undefined): { refs: H3ExampleReference[]; text: string } {
  const text = source || ''
  const lines = text.split('\n')
  if (lines[0] !== HEADER) return { refs: [], text }
  const refs: H3ExampleReference[] = []
  let index = 1
  for (; index < lines.length; index++) {
    const match = /^> - \[(.*)\]\(stimma-h3:(\d{6})\)$/.exec(lines[index])
    if (!match) break
    refs.push({ id: match[2], label: match[1] })
  }
  if (!refs.length || lines[index] !== GUIDANCE) return { refs: [], text }
  index++
  if (lines[index] === '') index++
  return { refs, text: lines.slice(index).join('\n') }
}

export type ChatMarkdownSegment =
  | { type: 'html'; content: string }
  | { type: 'media'; mediaId: number }
  | { type: 'h3-example'; id: string; label: string }

export function splitChatMarkdown(html: string): ChatMarkdownSegment[] {
  // Markers are generated by the Markdown renderer; data attributes survive sanitization.
  const markers = /<!--STIMMA_MEDIA:(\d+)-->|<button\b[^>]*data-stimma-h3="(\d{6})"[^>]*data-h3-label="([^"]*)"[^>]*>[^]*?<\/button>/g
  const segments: ChatMarkdownSegment[] = []
  let start = 0
  for (const match of html.matchAll(markers)) {
    if (match.index! > start) segments.push({ type: 'html', content: html.slice(start, match.index) })
    if (match[1]) segments.push({ type: 'media', mediaId: Number(match[1]) })
    else {
      let label = match[3]
      try { label = decodeURIComponent(label) } catch { /* Malformed raw HTML must remain renderable. */ }
      segments.push({ type: 'h3-example', id: match[2], label })
    }
    start = match.index! + match[0].length
  }
  if (start < html.length) segments.push({ type: 'html', content: html.slice(start) })
  return segments.length ? segments : [{ type: 'html', content: html }]
}
